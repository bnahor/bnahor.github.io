// Regenerates src/data/contributions.ts from the GitHub contributions calendar.
//
// The total and the monthly series are both derived from the same calendar, so
// they always agree with each other. Run by the "Refresh GitHub Contributions
// Data" workflow with a token; when no token is available (e.g. a local build),
// it leaves the committed file untouched so nothing breaks or goes empty.
import fs from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT = path.resolve(__dirname, '..');
const OUTPUT = path.join(ROOT, 'src', 'data', 'contributions.ts');
const USERNAME = process.env.GITHUB_USERNAME || 'bnahor';
const TOKEN = process.env.GITHUB_TOKEN || '';
const MONTHS = 12;

const QUERY = `
  query PortfolioContributions($login: String!, $from: DateTime!, $to: DateTime!) {
    user(login: $login) {
      contributionsCollection(from: $from, to: $to) {
        contributionCalendar {
          weeks {
            contributionDays {
              date
              contributionCount
            }
          }
        }
      }
    }
  }
`;

const MONTH_NAMES = [
  'Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun',
  'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec',
];

function trailingMonths(reference) {
  const months = [];
  for (let offset = MONTHS - 1; offset >= 0; offset -= 1) {
    const date = new Date(Date.UTC(reference.getUTCFullYear(), reference.getUTCMonth() - offset, 1));
    months.push({
      key: `${date.getUTCFullYear()}-${date.getUTCMonth()}`,
      month: MONTH_NAMES[date.getUTCMonth()],
      year: date.getUTCFullYear(),
      commits: 0,
    });
  }
  return months;
}

async function fetchCalendar() {
  const to = new Date();
  const from = new Date(Date.UTC(to.getUTCFullYear(), to.getUTCMonth() - (MONTHS - 1), 1));

  const response = await fetch('https://api.github.com/graphql', {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      Authorization: `Bearer ${TOKEN}`,
    },
    body: JSON.stringify({
      query: QUERY,
      variables: { login: USERNAME, from: from.toISOString(), to: to.toISOString() },
    }),
  });

  if (!response.ok) {
    throw new Error(`GitHub GraphQL request failed: ${response.status}`);
  }

  const payload = await response.json();
  if (payload.errors?.length) {
    throw new Error(`GitHub GraphQL returned errors: ${payload.errors[0].message}`);
  }

  const calendar = payload.data?.user?.contributionsCollection?.contributionCalendar;
  if (!calendar) {
    throw new Error('GitHub GraphQL response missing contribution calendar');
  }

  const buckets = trailingMonths(to);
  const index = new Map(buckets.map((bucket) => [bucket.key, bucket]));

  for (const week of calendar.weeks ?? []) {
    for (const day of week.contributionDays ?? []) {
      const date = new Date(`${day.date}T00:00:00Z`);
      const bucket = index.get(`${date.getUTCFullYear()}-${date.getUTCMonth()}`);
      if (bucket) bucket.commits += day.contributionCount ?? 0;
    }
  }

  return { asOf: to.toISOString().slice(0, 10), buckets };
}

function render({ asOf, buckets }) {
  const rows = buckets
    .map((b) => `  { month: '${b.month}', year: ${b.year}, commits: ${b.commits} },`)
    .join('\n');

  return `// Committed fallback for the commit-cadence instrument in the hero.
//
// This file is regenerated by scripts/fetch-github-contributions.mjs (run by the
// "Refresh GitHub Contributions Data" workflow) from the GitHub contributions
// calendar, so the total and the monthly series always come from the same source
// and agree with each other. The values below are the last snapshot; \`asOf\`
// records when they were captured so the UI can label the data honestly.
export const contributionsAsOf = '${asOf}';

export type CommitMonth = {
  month: string;
  year: number;
  commits: number;
};

export const commitCadence: readonly CommitMonth[] = [
${rows}
];

export const contributionTotal = commitCadence.reduce((sum, item) => sum + item.commits, 0);
`;
}

async function main() {
  if (!TOKEN) {
    console.warn('No GITHUB_TOKEN provided; leaving src/data/contributions.ts untouched.');
    return;
  }

  try {
    const data = await fetchCalendar();
    await fs.writeFile(OUTPUT, render(data), 'utf8');
    const total = data.buckets.reduce((sum, b) => sum + b.commits, 0);
    console.log(`Wrote src/data/contributions.ts (${total} contributions, as of ${data.asOf}).`);
  } catch (error) {
    console.error(error instanceof Error ? error.message : error);
    console.warn('Leaving src/data/contributions.ts untouched.');
  }
}

main();
